const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
app.setPath('userData', path.join(require('node:os').tmpdir(), 'pawtalk-connection-ui-' + process.pid));
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1100, height: 850, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, backgroundThrottling: false } });
  const run = source => win.webContents.executeJavaScript(source, true);
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
  const until = async source => { for (let i = 0; i < 100; i++) { if (await run(source)) return; await delay(50); } throw Error('Timed out: ' + source); };
  const capture = async name => { await delay(180); await fs.mkdir('release/qa', { recursive: true }); await fs.writeFile(`release/qa/${name}.png`, (await win.webContents.capturePage()).toPNG()); };
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  try {
    await win.loadURL(process.env.PAWTALK_UI_TEST_URL + '/tests/connection-ui.html');
    await until('!!document.querySelector("button")');
    win.focus();win.webContents.focus();
    for (const language of ['ru', 'en']) for (const reduced of [false, true]) {
      win.webContents.debugger.attach('1.3');
      await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: reduced ? 'reduce' : 'no-preference' }] });
      win.webContents.debugger.detach();
      await run(`fixture.language('${language}');fixture.feedback(false);fixture.state('connecting');fixture.state('connected')`);
      await run(`document.querySelector('button').dispatchEvent(new MouseEvent('mouseover',{bubbles:true}))`);
      assert.equal(await run(`!!document.querySelector('[role=tooltip]')`), false, 'hover has a delay');
      await until(`!!document.querySelector('[role=tooltip]')`);
      assert.equal(await run(`document.querySelectorAll('.connection-chart,dl,.connection-debug-button').length`), 0, 'hover is ping only');
      await run(`fixture.sample()`);
      await until(`document.querySelector('[role=tooltip]').textContent==='${language === 'en' ? '83 ms' : '83 мс'}'`);
      await capture(`connection-hover-${language}`);
      await run(`document.querySelector('button').dispatchEvent(new MouseEvent('mouseout',{bubbles:true}))`);
      await until(`!document.querySelector('[role=tooltip]')`);
      await run(`document.querySelector('button').click()`);
      await until(`!!document.querySelector('.connection-summary')`);
      assert.equal(await run(`document.querySelectorAll('.connection-chart').length`), 1, 'summary has one ping graph');
      assert.equal(await run(`document.querySelectorAll('dl>div').length`), 3);
      await run(`window.originalPanel=document.querySelector('.connection-summary');fixture.render();fixture.sample(false)`);
      assert.equal(await run(`originalPanel===document.querySelector('.connection-summary')`), true);
      assert.equal(await run(`fixture.snapshot().rtt.filter(p=>p.value!==undefined).length`), 1);
      assert.equal(await run(`document.querySelectorAll('.connection-summary dt')[2].textContent`),language==='en'?'Outgoing audio packet loss':'Потеря исходящих аудиопакетов');
      assert.equal(await run(`document.querySelectorAll('.connection-summary dd')[2].textContent`),'—','no fabricated zero before feedback');
      await run(`fixture.feedback(true);fixture.sample()`);
      await until(`document.querySelectorAll('.connection-summary dd')[2].textContent==='${language === 'en' ? '12.5 %' : '12,5 %'}'`);
      await run(`fixture.feedback(false);fixture.sample()`);
      await until(`document.querySelectorAll('.connection-summary dd')[2].textContent==='—'`);
      await run(`document.querySelector('.connection-summary').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`);
      assert.equal(await run(`!!document.querySelector('.connection-summary')`), true, 'inside click keeps summary open');
      await capture(`connection-summary-${language}`);
      await run(`document.body.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`);
      await until(`!document.querySelector('.connection-summary')`);
      await run(`document.querySelector('button').click()`);
      await until(`!!document.querySelector('.connection-debug-button')`);
      await run(`document.querySelector('.connection-debug-button').click()`);
      await until(`!!document.querySelector('dialog[open]')`);
      assert.equal(await run(`!!document.querySelector('.connection-summary')`), false, 'debug replaces summary');
      assert.equal(await run(`document.querySelectorAll('[role=tab]').length`), 2);
      assert.equal(await run(`document.querySelector('dialog').textContent.includes('${language === 'en' ? 'Average send delay' : 'Средняя задержка отправки'}')`),false);
      assert.equal(await run(`document.querySelector('dialog').textContent.includes('${language === 'en' ? 'Unavailable metrics are not replaced with zeros.' : 'Недоступные показатели не подменяются нулями.'}')`),false);
      assert.equal(await run(`document.querySelectorAll('[role=tabpanel] .rtc-metric').length`), 1, 'only measured transport RTT is visible');
      assert.equal(await run(`document.querySelectorAll('.rtc-metric figcaption').length`), 0, 'debug graphs have no duplicated upper bound');
      assert.ok(await run(`Array.from(document.querySelectorAll('.rtc-metric-value>span')).every(node=>node.textContent.trim() && !/Недоступно|Unavailable/.test(node.textContent))`));
      await run(`fixture.details({transportBytesSent:0,transportPacketsReceived:0})`);
      await until(`document.querySelectorAll('.rtc-metric').length===3`);
      assert.equal(await run(`document.querySelector('[data-metric=transportBytesSent] .rtc-metric-value>span').textContent`),'0 KB','real zero stays visible');
      await run(`fixture.details({transportBytesSent:NaN,transportPacketsReceived:undefined})`);
      await until(`document.querySelectorAll('.rtc-metric').length===1`);
      assert.equal(await run(`document.querySelectorAll('[data-metric=transportBytesSent],[data-metric=transportPacketsReceived]').length`),0,'invalid current values hide historical graphs');
      await run(`fixture.race()`);
      await until(`document.querySelector('.rtc-sidebar').textContent.includes('${language === 'en' ? 'Reconnecting' : 'Переподключение'}')`);
      assert.equal(await run(`fixture.snapshot().rtt.at(-1).value`), undefined);
      assert.equal(await run(`document.querySelectorAll('.rtc-metric').length`), 0, 'missing current values hide entire blocks including old graphs');
      await run(`(async()=>{fixture.state('connected');await fixture.sample();await fixture.fail()})()`);
      assert.equal(await run(`fixture.snapshot().rtt.at(-1).value`), undefined);
      await run(`fixture.sample()`);
      for (const theme of ['light', 'dark']) {
        await run(`fixture.theme('${theme}')`);
        await capture(`connection-transport-${language}-${theme}`);
        await run(`document.querySelectorAll('[role=tab]')[1].click()`);
        await until(`document.querySelector('[role=tab][aria-selected=true]').textContent==='${language === 'en' ? 'Outbound' : 'Исходящие'}'`);
        assert.ok(await run(`document.querySelector('[role=tabpanel]').textContent.includes('audio/opus')`));
        assert.equal(await run(`document.querySelectorAll('.rtc-metric figcaption').length`), 0);
        assert.ok(await run(`Array.from(document.querySelectorAll('.rtc-metric-value>span')).every(node=>node.textContent.trim() && !/Недоступно|Unavailable/.test(node.textContent))`));
        await capture(`connection-outbound-${language}-${theme}`);
        for (const zoom of [0.8,1.5]) {
          win.webContents.setZoomFactor(zoom); await delay(100);
          assert.ok(await run(`(()=>{const r=document.querySelector('dialog').getBoundingClientRect();return r.left>=0&&r.top>=0&&r.right<=innerWidth&&r.bottom<=innerHeight})()`));
        }
        win.webContents.setZoomFactor(1); await delay(100);
        await run(`document.querySelectorAll('[role=tab]')[1].dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true}))`);
        await until(`document.querySelectorAll('[role=tab]')[0].getAttribute('aria-selected')==='true'`);
      }
      win.setSize(380,420);await delay(120);
      assert.ok(await run(`(()=>{const r=document.querySelector('dialog').getBoundingClientRect();return r.left>=0&&r.top>=0&&r.right<=innerWidth&&r.bottom<=innerHeight})()`));
      win.setSize(1100,850);await delay(100);
      win.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});win.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'});
      await until(`!document.querySelector('dialog[open]')`);
      assert.ok(await run(`document.activeElement===document.querySelector('button')`),'close returns focus to signal');
      await run(`document.querySelector('button').blur();document.querySelector('button').focus()`);
      await until(`!!document.querySelector('[role=tooltip]')`);
      await run(`window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}))`);
      await until(`!document.querySelector('[role=tooltip]')`);
      await run(`document.querySelectorAll('button')[1].click()`);
      await until(`!!document.querySelector('.connection-popover[role=dialog]')`);
      assert.equal(await run(`document.querySelectorAll('.connection-chart,.connection-debug-button').length`),0,'peer summary stays compact');
      assert.equal(await run(`document.querySelectorAll('dl>div').length`),2);
      await run(`document.body.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));document.activeElement.blur()`);
    }
    await run(`fixture.disconnect()`);
    assert.equal(await run(`fixture.snapshot().rtt.length+fixture.snapshot().loss.length+Object.keys(fixture.snapshot().series).length`),0);
    assert.deepEqual(errors,[]);
    console.log('PASS ping-only hover, click summary, outside dismissal, debug modal/tabs/Escape/focus, RU/EN, themes, zoom, reduced motion, collector/reconnect/reset and compact peers');
    app.quit();
  } catch(error){console.error(error);app.exit(1);}
});
