import { createServer } from 'vite';
import { spawn } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const built = process.argv.includes('--built');
const server = built ? null : await createServer({ server: { host: '127.0.0.1', port: 5186, strictPort: true } });
await server?.listen();
const env = { ...process.env, PAWTALK_UI_TEST_URL: built ? pathToFileURL(path.resolve('dist/index.html')).href : 'http://127.0.0.1:5186' };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(require('electron'), ['tests/ui-flow.cjs'], { env, stdio: 'inherit', windowsHide: true });
child.on('error', async e => { console.error(e); await server?.close(); process.exit(1); });
child.on('exit', async code => { await server?.close(); process.exit(code || 0); });
