import { createServer } from 'vite';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import './prepare-rnnoise.mjs';
const server = await createServer({ server: { host: '127.0.0.1', port: 5194, strictPort: true } });
await server.listen();
const env = { ...process.env, PAWTALK_UI_TEST_URL: 'http://127.0.0.1:5194' };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(createRequire(import.meta.url)('electron'), ['tests/connection-ui.cjs'], { env, windowsHide: true, stdio: 'inherit' });
child.on('error', async error => { console.error(error); await server.close(); process.exit(1); });
child.on('exit', async code => { await server.close(); process.exit(code || 0); });
